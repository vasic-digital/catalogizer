"""fence_lib.py - shared helpers of the coverage exclusion fence (T200, review round 1 of WP-23: WF11 I5, I6). Imported by check_exclusions.py and bashcov.py.

  glob_re(pattern)            one glob dialect for the whole tool: `**` crosses `/`, `*` and `?` do not, a trailing `/` or `/**` names a directory
                              (replaces fnmatch, whose `*` crosses `/` and which therefore matched `src/*.go` against `src/a/b.go`)
  matches(pattern, rel)       True when the relative path is named by the pattern
  list_files(root)            the files of an application root: `git ls-files --cached --others --exclude-standard` when the root is inside a work tree (tracked and new
                              files, never ignored build output), else a walk without `.git`; relative POSIX paths, sorted
  extract_applied(kind, cfg)  the exclusion patterns a measuring tool's own config applies (read from the config text, never from a hand-kept list)
  class_evidence(cls, rel, abs_path)  does THIS file look like the class its entry claims? (the content half of 11.4.224 E)
"""
import os, re, subprocess

GENERATED_RE = re.compile(rb"(?i)code generated|do not edit|@generated|auto-?generated|generated by|this file was generated")
GENERATED_DIRS = {"generated", "__generated__", "gen", "build", "dist", "out", "target", ".gradle", "schemas"}
VENDORED_DIRS = {"vendor", "node_modules", "third_party", "thirdparty", "third-party", "external", "opensource"}
FIXTURE_DIRS = {"test", "tests", "testdata", "fixtures", "fixture", "mocks", "mock", "golden", "__tests__", "__mocks__", "e2e", "spec", "specs", "testing", "test-utils", "test_utils", "androidtest"}
# a test FILE name: test_*, *_test.*, *.test.*, *.spec.*, or a CamelCase name that ENDS in Test/Tests (FooTest.kt); `TestHelper.kt` is not one (review m10: the glob **/*Test*.* also names those)
FIXTURE_FILE_RE = re.compile(r"(^test_|_test\.|\.test\.|\.spec\.|[A-Za-z0-9](Test|Tests)\.[A-Za-z]+$)")


def glob_re(pattern):
    p = pattern.strip()
    if p.startswith("./"):
        p = p[2:]
    dir_only = p.endswith("/") or p.endswith("/**")
    if p.endswith("/**"):
        p = p[:-3]
    p = p.rstrip("/")
    out = []; i = 0
    while i < len(p):
        c = p[i]
        if c == "*":
            if p[i:i + 3] == "**/":
                out.append("(?:.*/)?"); i += 3; continue
            if p[i:i + 2] == "**":
                out.append(".*"); i += 2; continue
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        else:
            out.append(re.escape(c))
        i += 1
    body = "".join(out)
    return re.compile("^" + body + ("(?:/.*)?" if dir_only else "(?:/.*)?") + "$")


def matches(pattern, rel):
    return bool(glob_re(pattern).match(rel))


def list_files(root):
    root = os.path.abspath(root)
    try:
        p = subprocess.run(["git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "."], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        names = [n for n in p.stdout.decode("utf-8", "replace").split("\0") if n]
        if p.returncode == 0 and names:
            return sorted(names)
    except OSError:
        pass
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d != ".git"]
        for f in fns:
            out.append(os.path.relpath(os.path.join(dp, f), root).replace(os.sep, "/"))
    return sorted(out)


def _strings(text):
    return [m.group(2) for m in re.finditer(r"(['\"])((?:\\.|(?!\1).)*)\1", text)]


def _array_after(text, anchor_re, start=0):
    m = anchor_re.search(text, start)
    if not m:
        return None
    i = text.find("[", m.end())
    if i < 0:
        return None
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "[": depth += 1
        elif text[j] == "]":
            depth -= 1
            if depth == 0:
                return _strings(text[i + 1:j])
    return None


def extract_applied(kind, cfg_path):
    """Returns (patterns, note, include). patterns is None when the config cannot be read or the tool block is not found (the caller refuses: an
    unreadable tool config is an UNVERIFIABLE used list, never an empty one). include is the list of positive scope patterns of a tool that has
    them (jest collectCoverageFrom), else None meaning every file of the root is in scope."""
    if kind == "none":
        return [], "the tool applies no exclusion", None
    try:
        text = open(cfg_path, encoding="utf-8").read()
    except OSError as e:
        return None, "cannot read %s: %s" % (cfg_path, e), None
    if kind == "vitest":
        m = re.search(r"\bcoverage\s*:\s*\{", text)
        if not m:
            return [], "no coverage block in %s: the tool excludes nothing from coverage" % os.path.basename(cfg_path), None
        arr = _array_after(text, re.compile(r"\bexclude\s*:"), m.end())
        return (arr if arr is not None else []), "coverage.exclude of %s" % os.path.basename(cfg_path), None
    if kind == "jest":
        arr = _array_after(text, re.compile(r"\bcollectCoverageFrom\s*:"))
        if arr is None:
            return [], "no collectCoverageFrom in %s" % os.path.basename(cfg_path), None
        return [a[1:] for a in arr if a.startswith("!")], "negated collectCoverageFrom of %s" % os.path.basename(cfg_path), [a for a in arr if not a.startswith("!")]
    if kind == "jacoco":
        m = re.search(r"\bfileFilter\s*=\s*listOf\s*\(", text)
        if not m:
            return None, "no fileFilter in %s" % os.path.basename(cfg_path), None
        depth = 1; j = m.end()
        while j < len(text) and depth:
            depth += (text[j] == "(") - (text[j] == ")"); j += 1
        return [s.replace("\\$", "$") for s in _strings(text[m.end():j - 1])], "jacoco fileFilter of %s" % os.path.basename(cfg_path), None
    if kind == "none":
        return [], "the tool applies no exclusion", None
    return None, "unknown tool kind %r" % kind, None


MEASURABLE = {"vitest": (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue"), "jest": (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"),
              "jacoco": (".kt", ".java", ".class")}


def class_evidence(cls, rel, abs_path):
    """True when the file is consistent with the class its entry claims; (False, why) otherwise. first-party has no content evidence (it needs a tracked item)."""
    parts = rel.split("/")
    if cls == "generated-code":
        if any(p in GENERATED_DIRS for p in parts[:-1]) or parts[-1] in ("R.class",) or re.match(r"^(R\$.*\.class|BuildConfig\..*|Manifest.*\..*)$", parts[-1]):
            return True, ""
        try:
            head = open(abs_path, "rb").read(4096)
        except OSError:
            return False, "unreadable"
        return (True, "") if GENERATED_RE.search(head) else (False, "no generated-code marker in the first 4 KiB and not in a generated directory")
    if cls == "vendored-third-party":
        return (True, "") if any(p in VENDORED_DIRS for p in parts[:-1]) else (False, "not under a vendored-third-party directory (%s)" % "/".join(sorted(VENDORED_DIRS)))
    if cls == "non-shipping-fixtures-and-golden-assets":
        if any(p.lower() in FIXTURE_DIRS for p in parts[:-1]) or FIXTURE_FILE_RE.search(parts[-1]):
            return True, ""
        return False, "not under a test/fixture directory and not a test file name"
    return True, ""
