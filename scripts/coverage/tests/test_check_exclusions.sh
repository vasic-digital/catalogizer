#!/usr/bin/env bash
# test_check_exclusions.sh - T200 (RED first). Oracle for scripts/coverage/check_exclusions.sh (docs/05 7.3, constitution 11.4.224 E): a coverage exclusion is
# legal only through a CHECKED-IN list, every entry justified from the closed class set {generated-code, vendored-third-party,
# non-shipping-fixtures-and-golden-assets}; a first-party exclusion additionally needs a tracked item. Legs: golden-good passes; an unlisted exclusion (a pattern the
# measuring tool uses that is not in the list), an unjustified entry, a first-party entry without a tracked item, an unknown class, an over-broad pattern
# and a schema/application mismatch each FAIL; the verdict is written to a JSON file. The paired mutations (G-GATE) are copies of the gate with ONE
# check removed; each must make this body FAIL. The mutation is also run against every real exclusion file by mutate_exclusions.sh.
# Usage: test_check_exclusions.sh [--no-mutations]    Env: GATE (the gate under test), MUTATION_RECORD
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
GATE="${GATE:-$HERE/../check_exclusions.sh}"
PASSES=0; FAILS=0
ok()  { PASSES=$((PASSES+1)); echo "PASS: $1"; }
bad() { FAILS=$((FAILS+1)); echo "FAIL: $1"; }
check() { if [ "$2" = "$3" ]; then ok "$1"; else bad "$1 (got '$2' want '$3')"; fi; }
T="$(mktemp -d "${TMPDIR:-/tmp}/chkexcl-test.XXXXXX")"; trap 'rm -rf "$T"' EXIT
[ -f "$GATE" ] || { bad "the gate scripts/coverage/check_exclusions.sh does not exist (T200)"; echo "Summary: PASS=$PASSES FAIL=$FAILS SKIP=0"; exit 1; }
mkdir -p "$T/app"
good() { cat >"$T/app/demo.yaml" <<'Y'
schema: coverage-exclusions/1
application: demo
exclusions:
  - path: "gen/schemas/**"
    class: generated-code
    justification: "files written by the framework code generator, regenerated by its build step"
  - path: "vendor/**"
    class: vendored-third-party
    justification: "third-party sources copied in unmodified, owned by their upstream"
  - path: "testdata/**"
    class: non-shipping-fixtures-and-golden-assets
    justification: "golden inputs and recorded outputs read only by tests, never shipped"
  - path: "legacy/old_parser.go"
    class: first-party
    tracked_item: ATM-1234
    justification: "shipped parser kept out of the figure until its rewrite lands, plan in the tracked item"
Y
}
run() { bash "$GATE" "$@" >"$T/out" 2>"$T/err"; RC=$?; }
good; run "$T/app/demo.yaml" --json "$T/verdict.json"
check "golden-good: exit 0" "$RC" 0
check "golden-good: the verdict file says PASS" "$(jq -r .verdict "$T/verdict.json" 2>/dev/null)" PASS
check "golden-good: the verdict names the application" "$(jq -r .application "$T/verdict.json" 2>/dev/null)" demo
check "golden-good: the verdict carries the sha256 of the checked file" "$(jq -r .sha256 "$T/verdict.json" 2>/dev/null)" "$(sha256sum <"$T/app/demo.yaml" | cut -d' ' -f1)"
check "golden-good: the first-party entry is reported as an honest gap" "$(jq -r '.first_party_entries | length' "$T/verdict.json" 2>/dev/null)" 1
# unlisted exclusion: a pattern the measuring tool uses is not in the list
printf '%s\n' 'gen/schemas/**' 'vendor/**' 'src/secret_dir/**' >"$T/used.txt"
run "$T/app/demo.yaml" --used "$T/used.txt" --json "$T/v2.json"
[ "$RC" = 1 ] && ok "unlisted exclusion: exit 1" || bad "unlisted exclusion: exit $RC"
grep -q 'src/secret_dir' "$T/err" && grep -qi 'unlisted' "$T/err" && ok "unlisted exclusion: stderr names the pattern" || bad "unlisted exclusion: stderr: $(cat "$T/err")"
check "unlisted exclusion: the verdict file says FAIL" "$(jq -r .verdict "$T/v2.json")" FAIL
printf '%s\n' 'gen/schemas/**' 'vendor/**' 'testdata/**' >"$T/used-ok.txt"
run "$T/app/demo.yaml" --used "$T/used-ok.txt"; check "golden-false: every used pattern is listed: exit 0" "$RC" 0
printf '%s\n' 'gen/schemas/' 'vendor' 'testdata/**' >"$T/used-norm.txt"
run "$T/app/demo.yaml" --used "$T/used-norm.txt"; check "a used pattern that names a listed directory in another spelling (dir/, dir) is listed: exit 0" "$RC" 0
# unjustified entry
good; python3 -I - "$T/app/demo.yaml" <<'PY'
import sys
s=open(sys.argv[1]).read(); s=s.replace('justification: "files written by the framework code generator, regenerated by its build step"','justification: ""'); open(sys.argv[1],"w").write(s)
PY
run "$T/app/demo.yaml"; [ "$RC" = 1 ] && grep -qi 'unjustified' "$T/err" && ok "unjustified entry: exit 1 naming it" || bad "unjustified entry: rc $RC: $(cat "$T/err")"
good; sed -i 's/justification: "third-party sources copied in unmodified, owned by their upstream"/justification: "x"/' "$T/app/demo.yaml"
run "$T/app/demo.yaml"; [ "$RC" = 1 ] && ok "a one-character justification is not a justification: exit 1" || bad "a one-character justification accepted"
# first-party without a tracked item
good; sed -i '/tracked_item: ATM-1234/d' "$T/app/demo.yaml"
run "$T/app/demo.yaml"; [ "$RC" = 1 ] && grep -qi 'tracked item' "$T/err" && grep -q 'old_parser' "$T/err" && ok "first-party entry without a tracked item: exit 1 naming it" || bad "first-party w/o item: rc $RC: $(cat "$T/err")"
good; sed -i 's/tracked_item: ATM-1234/tracked_item: later/' "$T/app/demo.yaml"
run "$T/app/demo.yaml"; [ "$RC" = 1 ] && ok "a tracked item that is not an item id is refused" || bad "a bogus tracked item accepted"
# unknown class, over-broad pattern, schema, application mismatch, unreadable file, duplicate path, path escaping the root
good; sed -i 's/class: vendored-third-party/class: whatever-i-like/' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && grep -q 'whatever-i-like' "$T/err" && ok "an unknown class is refused naming it" || bad "unknown class accepted"
good; sed -i 's#path: "vendor/\*\*"#path: "**"#' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && grep -qi 'over-broad' "$T/err" && ok "an over-broad pattern (**) is refused" || bad "over-broad pattern accepted"
good; sed -i 's#path: "vendor/\*\*"#path: "/etc/passwd"#' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && ok "an absolute path is refused" || bad "absolute path accepted"
good; sed -i 's#path: "vendor/\*\*"#path: "../outside/**"#' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && ok "a path with .. is refused" || bad ".. accepted"
good; sed -i 's#path: "testdata/\*\*"#path: "vendor/**"#' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && grep -qi 'duplicate' "$T/err" && ok "a duplicate path is refused" || bad "duplicate path accepted"
good; sed -i 's/^schema: coverage-exclusions\/1/schema: coverage-exclusions\/7/' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && ok "a wrong schema is refused" || bad "wrong schema accepted"
good; sed -i 's/^application: demo/application: other/' "$T/app/demo.yaml"; run "$T/app/demo.yaml"
[ "$RC" = 1 ] && grep -qi 'application' "$T/err" && ok "an application that differs from the file stem is refused" || bad "application mismatch accepted"
run "$T/app/missing.yaml"; check "an unreadable file is a refusal, never a pass" "$RC" 1
run; check "no argument is a usage error" "$RC" 2
# an empty exclusion list is a valid, honest statement (no exclusions); a missing key is not
printf 'schema: coverage-exclusions/1\napplication: empty\nexclusions: []\n' >"$T/app/empty.yaml"; run "$T/app/empty.yaml"; check "an explicit empty list passes" "$RC" 0
printf 'schema: coverage-exclusions/1\napplication: nokey\n' >"$T/app/nokey.yaml"; run "$T/app/nokey.yaml"; check "a file without the exclusions key is refused" "$RC" 1
# with --root: an entry that matches no file is reported stale (a note, not a failure); one that matches is counted
mkdir -p "$T/root/vendor" "$T/root/gen/schemas"; echo x >"$T/root/vendor/a.go"; echo y >"$T/root/gen/schemas/b.json"
good; run "$T/app/demo.yaml" --root "$T/root" --json "$T/v3.json"
check "--root: still exit 0 (a stale entry is a note)" "$RC" 0
check "--root: the vendor entry matches one file" "$(jq -r '.entries[] | select(.path=="vendor/**") | .matched_files' "$T/v3.json")" 1
check "--root: the testdata entry matches none and is reported stale" "$(jq -r '.entries[] | select(.path=="testdata/**") | .stale' "$T/v3.json")" true

if [ "${1:-}" != --no-mutations ] && [ -z "${GATE_MUTANT:-}" ]; then
  REC="${MUTATION_RECORD:-$T/mutations.txt}"; : >"$REC"
  PY="$(cd "$(dirname "$GATE")" && pwd)/check_exclusions.py"
  mut() { # mut NAME OLD NEW
    local name="$1" old="$2" new="$3" d="$T/mut-$1"; rm -rf "$d"; mkdir -p "$d"; cp "$(dirname "$GATE")/check_exclusions.sh" "$d/"; cp "$PY" "$d/"
    python3 -I - "$d/check_exclusions.py" "$old" "$new" <<'PY' || { bad "mutation $name: anchor not unique"; return; }
import sys
s=open(sys.argv[1]).read()
if s.count(sys.argv[2])!=1: sys.exit(1)
open(sys.argv[1],"w").write(s.replace(sys.argv[2],sys.argv[3]))
PY
    if GATE="$d/check_exclusions.sh" GATE_MUTANT=1 bash "${BASH_SOURCE[0]}" --no-mutations >"$T/mut-$name.out" 2>&1; then bad "mutation $name SURVIVED"; echo "SURVIVED $name" >>"$REC"
    else ok "mutation $name caught ($(grep -c '^FAIL:' "$T/mut-$name.out") failing legs)"; echo "CAUGHT $name: $(grep '^FAIL:' "$T/mut-$name.out" | head -2 | cut -c1-110 | tr '\n' '|')" >>"$REC"; fi
  }
  mut tracked-item-ignored 'if cls == "first-party" and not item_ok:' 'if False:'
  mut justification-ignored 'if len(just) < MIN_JUST:' 'if False:'
  mut unlisted-ignored 'if used_unlisted:' 'if False:'
  mut class-unchecked 'if cls not in CLASSES:' 'if False:'
  mut overbroad-ignored 'if overbroad(p):' 'if False:'
  mut duplicate-ignored 'if p in seen:' 'if False:'
  mut exit-masked 'sys.exit(1 if problems else 0)' 'sys.exit(0)'
fi
echo "Summary: PASS=$PASSES FAIL=$FAILS SKIP=0"
[ "$FAILS" = 0 ]
