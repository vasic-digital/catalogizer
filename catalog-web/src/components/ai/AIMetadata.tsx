import React from 'react';

// Types for AI metadata extraction and automation
interface ExtractedMetadata {
  id: string;
  title: string;
  description: string;
  tags: string[];
  categories: string[];
  confidence: number;
  source: 'ai' | 'manual' | 'hybrid';
  extractedFields: {
    [key: string]: {
      value: unknown;
      confidence: number;
      source: string;
    };
  };
}

interface AutomationRule {
  id: string;
  name: string;
  description: string;
  trigger: {
    type: 'content_added' | 'schedule' | 'manual' | 'content_updated';
    conditions: {
      field: string;
      operator: 'equals' | 'contains' | 'starts_with' | 'regex';
      value: unknown;
    }[];
  };
  actions: {
    type: 'categorize' | 'tag' | 'move_to_collection' | 'send_notification' | 'transform';
    parameters: unknown;
  }[];
  enabled: boolean;
  priority: 'low' | 'medium' | 'high';
  executionCount: number;
  lastExecuted?: string;
}

interface ContentQuality {
  score: number;
  factors: {
    completeness: number;
    accuracy: number;
    engagement: number;
    relevance: number;
  };
  recommendations: string[];
  improvements: {
    type: 'add_metadata' | 'improve_description' | 'add_tags' | 'enhance_content';
    description: string;
    impact: 'high' | 'medium' | 'low';
  }[];
}

interface SmartContent {
  id: string;
  type: 'video' | 'image' | 'document' | 'audio' | 'mixed';
  qualityScore: number;
  autoGenerated: {
    title: string;
    description: string;
    tags: string[];
    thumbnail?: string;
    preview?: string;
  };
  metadata: ExtractedMetadata;
  processing: {
    status: 'pending' | 'processing' | 'completed' | 'failed';
    stage: string;
    progress: number;
  };
}

/**
 * The server has no AI engine behind these panels. The earlier version used a
 * client-side mock service (timers, Math.random scores and canned text) and
 * presented the output as real analysis. They now say plainly that the feature
 * is unavailable and show no invented data (CAT-001, constitution 11.4.289).
 * Props are kept so existing pages compile unchanged.
 */

interface UnavailablePanelProps {
  title: string;
  testId: string;
  reason: string;
}

const UnavailablePanel: React.FC<UnavailablePanelProps> = ({ title, testId, reason }) => (
  <div className="bg-white rounded-lg shadow p-6" data-testid={testId}>
    <h3 className="text-lg font-semibold text-gray-900 mb-2">{title}</h3>
    <p className="font-medium text-gray-700">Unavailable</p>
    <p className="text-sm text-gray-500">{reason}</p>
  </div>
);

interface AIMetadataExtractorProps {
  content: {
    title?: string;
    description?: string;
    fileType?: string;
    size?: number;
    duration?: number;
    url?: string;
  };
  onMetadataExtracted: (metadata: ExtractedMetadata) => void;
}
interface AIAutomationRulesProps {
  onRuleToggle: (ruleId: string, enabled: boolean) => void;
  onRuleExecute: (ruleId: string) => void;
}
interface AIContentQualityAnalyzerProps {
  content: {
    title?: string;
    thumbnail?: string;
    description?: string;
    tags?: string[];
    categories?: string[];
  };
  onQualityImprovement: (improvement: string) => void;
}

export const AIMetadataExtractor: React.FC<AIMetadataExtractorProps> = () => (
  <UnavailablePanel title="AI Metadata Extractor" testId="ai-extractor-unavailable" reason="This server has no metadata extraction engine, so no metadata can be proposed." />
);

export const AIAutomationRules: React.FC<AIAutomationRulesProps> = () => (
  <UnavailablePanel title="Automation Rules" testId="ai-automation-unavailable" reason="This server has no automation engine, so rules cannot be created or run." />
);

export const AIContentQualityAnalyzer: React.FC<AIContentQualityAnalyzerProps> = () => (
  <UnavailablePanel title="Content Quality Analyzer" testId="ai-quality-unavailable" reason="This server has no quality-analysis engine, so no scores can be shown." />
);

export type { ExtractedMetadata, AutomationRule, ContentQuality, SmartContent };
