package tests

import (
	"fmt"
	"net"
	"os"
	"strings"
	"testing"
	"time"
)

// The test infrastructure is a PER-RUN stack (scripts/test-infra/up.sh, docker-compose.test-infra.yml): random loopback host ports and generated credentials,
// no fixed port and no literal credential (T129; WF12 F1). up.sh writes them to a mode 0600 env file, .audit/test-infra/catalogizer-test-<id>/env, and prints
// its op_id and ports. Point this package at that file with CATALOGIZER_TEST_INFRA_ENV; an explicit FTP_TEST_SERVER / SMB_TEST_SERVER / WEBDAV_TEST_SERVER /
// NFS_TEST_SERVER and *_TEST_USER / *_TEST_PASS still override a single value. With neither, every Require* skips and says how to start the stack.
// The user-space NFS server publishes no host port (its clients run on the project network), so NFS is reachable here only through an explicit NFS_TEST_SERVER.
const (
	// EnvFileVariable names the variable that holds the path of the per-run env file written by scripts/test-infra/up.sh.
	EnvFileVariable = "CATALOGIZER_TEST_INFRA_ENV"

	// startHint is appended to every skip message.
	startHint = "start the stack with: scripts/test-infra/up.sh --build-id <id>  and set " + EnvFileVariable + " to the env file it names (.audit/test-infra/catalogizer-test-<id>/env)"

	// connectionTimeout is the maximum time to wait when probing a service.
	// Kept short (1 second) so tests skip quickly when infrastructure is absent.
	connectionTimeout = 1 * time.Second
)

// InfraStatus holds the reachability state of all test infrastructure services.
type InfraStatus struct {
	FTP    bool
	SMB    bool
	WebDAV bool
	NFS    bool
}

// TestInfraCredentials provides the credentials of the per-run test infrastructure services (generated by scripts/test-infra/gen_env.sh).
type TestInfraCredentials struct {
	Username string
	Password string
}

// FTPCredentials returns the FTP test credentials of the per-run stack (empty when no stack is configured).
func FTPCredentials() TestInfraCredentials {
	return TestInfraCredentials{
		Username: envOrRunEnv("FTP_TEST_USER", "TI_FTP_USER"),
		Password: envOrRunEnv("FTP_TEST_PASS", "TI_FTP_PASSWORD"),
	}
}

// SMBCredentials returns the SMB test credentials of the per-run stack (empty when no stack is configured).
func SMBCredentials() TestInfraCredentials {
	return TestInfraCredentials{
		Username: envOrRunEnv("SMB_TEST_USER", "TI_SMB_USER"),
		Password: envOrRunEnv("SMB_TEST_PASS", "TI_SMB_PASSWORD"),
	}
}

// WebDAVCredentials returns the WebDAV test credentials of the per-run stack (empty when no stack is configured).
func WebDAVCredentials() TestInfraCredentials {
	return TestInfraCredentials{
		Username: envOrRunEnv("WEBDAV_TEST_USER", "TI_WEBDAV_USER"),
		Password: envOrRunEnv("WEBDAV_TEST_PASS", "TI_WEBDAV_PASSWORD"),
	}
}

// SMBShareName returns the SMB test share name (docker-compose.test-infra.yml declares the share `testshare`).
func SMBShareName() string {
	if v := os.Getenv("SMB_TEST_SHARE"); v != "" {
		return v
	}
	return "testshare"
}

// ---------------------------------------------------------------------------
// Require* functions — call these at the start of integration tests.
// They skip the test with t.Skip() if the corresponding service is not
// reachable, rather than failing. This allows the full test suite to run
// even when test infrastructure is partially or fully absent.
// ---------------------------------------------------------------------------

// RequireFTP skips the test if the FTP test server is not reachable.
// Returns the FTP server address for use in test configuration.
func RequireFTP(t *testing.T) string {
	t.Helper()
	addr := ftpAddr()
	if !isReachable(addr) {
		t.Skipf("FTP test server not reachable at %s — "+startHint, addr)
	}
	return addr
}

