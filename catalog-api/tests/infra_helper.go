// RequireAnyInfra skips the test if none of the test infrastructure services
// are reachable. Useful for tests that can work with any available protocol.
func RequireAnyInfra(t *testing.T) InfraStatus {
	t.Helper()
	status := ProbeInfra()
	if !status.FTP && !status.SMB && !status.WebDAV && !status.NFS {
		t.Skip("No test infrastructure services reachable — " + startHint)
	}
	return status
}

// RequireAllInfra skips the test if any test infrastructure service is not
// reachable. Useful for comprehensive protocol comparison tests.
func RequireAllInfra(t *testing.T) InfraStatus {
	t.Helper()
	status := ProbeInfra()
	missing := []string{}
	if !status.FTP {
		missing = append(missing, "FTP")
	}
	if !status.SMB {
		missing = append(missing, "SMB")
	}
	if !status.WebDAV {
		missing = append(missing, "WebDAV")
	}
	if !status.NFS {
		missing = append(missing, "NFS")
	}
	if len(missing) > 0 {
		t.Skipf("Test infrastructure services not reachable: %v — "+startHint, missing)
	}
	return status
}

// ProbeInfra checks which test infrastructure services are currently reachable.
// Does not call t.Skip; returns the status for the caller to decide.
func ProbeInfra() InfraStatus {
	return InfraStatus{
		FTP:    isReachable(ftpAddr()),
		SMB:    isReachable(smbAddr()),
		WebDAV: isReachable(webdavAddr()),
		NFS:    isReachable(nfsAddr()),
	}
}

// String returns a human-readable summary of the infrastructure status.
func (s InfraStatus) String() string {
	status := func(ok bool) string {
		if ok {
			return "UP"
		}
		return "DOWN"
	}
	return fmt.Sprintf("FTP=%s SMB=%s WebDAV=%s NFS=%s",
		status(s.FTP), status(s.SMB), status(s.WebDAV), status(s.NFS))
}

// AvailableCount returns how many infrastructure services are reachable.
func (s InfraStatus) AvailableCount() int {
	count := 0
	if s.FTP {
		count++
	}
	if s.SMB {
		count++
	}
	if s.WebDAV {
		count++
	}
	if s.NFS {
		count++
	}
	return count
}

// ---------------------------------------------------------------------------
// Address resolution — env var overrides for non-default setups
// ---------------------------------------------------------------------------

func ftpAddr() string {
	return addrFor("FTP_TEST_SERVER", "TI_PORT_FTP")
}

func smbAddr() string {
	return addrFor("SMB_TEST_SERVER", "TI_PORT_SMB")
}

func webdavAddr() string {
	return addrFor("WEBDAV_TEST_SERVER", "TI_PORT_WEBDAV")
}

// nfsAddr: the user-space NFS server publishes no host port; only an explicit NFS_TEST_SERVER names one.
func nfsAddr() string {
	return os.Getenv("NFS_TEST_SERVER")
}

// addrFor returns the explicit override, else 127.0.0.1:<port of the per-run env file>, else "" (not configured).
func addrFor(override, portKey string) string {
	if v := os.Getenv(override); v != "" {
		return v
	}
	if port := runEnv()[portKey]; port != "" {
		return "127.0.0.1:" + port
	}
	return ""
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

// isReachable attempts a TCP connection to the given address with a short
// timeout. Returns true if the connection succeeds, false otherwise.
// This is a lightweight probe — it does not perform protocol handshakes.
func isReachable(addr string) bool {
	if addr == "" {
		return false
	}
	conn, err := net.DialTimeout("tcp", addr, connectionTimeout)
	if err != nil {
		return false
	}
	conn.Close()
	return true
}

// envOrRunEnv reads an explicit override variable, else the key of the per-run env file, else "".
func envOrRunEnv(override, key string) string {
	if v := os.Getenv(override); v != "" {
		return v
	}
	return runEnv()[key]
}

// runEnv parses the per-run env file named by CATALOGIZER_TEST_INFRA_ENV (KEY=VALUE lines written by scripts/test-infra/gen_env.sh; data, never evaluated).
// An unset variable or an unreadable file yields an empty map: the services then count as not configured.
func runEnv() map[string]string {
	out := map[string]string{}
	path := os.Getenv(EnvFileVariable)
	if path == "" {
		return out
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return out
	}
	for _, line := range strings.Split(string(raw), "\n") {
		if k, v, ok := strings.Cut(line, "="); ok && strings.HasPrefix(k, "TI_") {
			out[k] = v
		}
	}
	return out
}
