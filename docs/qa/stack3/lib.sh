#!/usr/bin/env bash
# Shared settings for the Catalogizer QA "stack 3" scripts (sourced by up.sh / down.sh / build.sh).
# Everything is overridable from the environment; secrets live ONLY in $QA_DIR/qa.env (mode 0600, outside the repo).
STACK="${STACK:-catqa3}"
POD="${STACK}"
QA_DIR="${QA_DIR:-$HOME/.cache/claude-tmp/${STACK}}"           # qa.env + website_dist + evidence live here, never in the repo
MEDIA_DIR="${MEDIA_DIR:-$HOME/.cache/claude-tmp/media-corpus}" # generated by scripts/test-infra/gen_media_fixtures.sh --out "$MEDIA_DIR"
MEDIA_MOUNT="${MEDIA_MOUNT:-/media}"                           # path inside the API container; point a storage root at it
API_PORT="${API_PORT:-38082}"; WEB_PORT="${WEB_PORT:-33020}"; WEBSITE_PORT="${WEBSITE_PORT:-33021}"
PG_PORT="${PG_PORT:-35434}";   REDIS_PORT="${REDIS_PORT:-36381}"  # loopback only
PG_IMAGE="${PG_IMAGE:-docker.io/library/postgres:15-alpine}"
REDIS_IMAGE="${REDIS_IMAGE:-docker.io/library/redis:7-alpine}"
NGINX_IMAGE="${NGINX_IMAGE:-docker.io/library/nginx:alpine}"
# Peer CIDR(s) the API trusts for X-Forwarded-For (gin SetTrustedProxies). Explicit list, never "auto"/0.0.0.0/0.
# MEASURED 2026-11-05 (docs/qa/stack3-verify-20261105/clientip_probe.txt): with pasta, a request that reaches the API through the monitoring nginx
# front door (pod catqa3mon, -T forward) AND a direct host-local request both arrive with the HOST's primary LAN address as TCP peer, so the proxy
# is trusted by trusting exactly that /32 (+ loopback). Remote LAN clients keep their own address and are NOT trusted. Override: TRUSTED_PROXIES=...
_hip="$(ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p' | head -n1)"
TRUSTED_PROXIES="${TRUSTED_PROXIES:-${_hip:+${_hip}/32,}127.0.0.1/32}"
